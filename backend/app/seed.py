def _d(s: str) -> date:
    return date.fromisoformat(s)


def _seed(db) -> None:
    store_ids = {}
    wh = Store(code=WH, name="总仓", is_warehouse=True)
    db.add(wh)
    db.flush()
    store_ids[WH] = wh.id
    for code, name in STORES:
        s = Store(code=code, name=name, is_warehouse=False)
        db.add(s)
        db.flush()
        store_ids[code] = s.id

    drug_ids = {}
    for code, name, spec, unit, mfr in DRUGS:
        d = Drug(code=code, name=name, spec=spec, unit=unit, manufacturer=mfr)
        db.add(d)
        db.flush()
        drug_ids[code] = d.id
    db.commit()

    # 汇总所有操作，按时间顺序重放，保证任何时点库存不为负
    ops = []  # (datetime, 优先级, 类型, 载荷)
    for drug_code, batch_no, prod, exp, supplier, qty, in_date in BATCHES:
        ops.append((datetime.fromisoformat(in_date + "T09:00:00"), 0, "inbound",
                    (drug_code, batch_no, prod, exp, supplier, qty)))
    for batch_no, frm, to, qty, ship, recv in TRANSFERS:
        ops.append((datetime.fromisoformat(ship + "T10:00:00"), 1, "ship",
                    (batch_no, frm, to, qty)))
        if recv:
            ops.append((datetime.fromisoformat(recv + "T15:00:00"), 2, "receive",
                        (batch_no, frm, to, qty)))
    for store, drug_code, qty, day, otype in SALES:
        ops.append((datetime.fromisoformat(day + "T16:00:00"), 3, "sale",
                    (store, drug_code, qty, otype)))
    batch_no, reason, day = QC_SUSPEND
    ops.append((datetime.fromisoformat(day + "T11:00:00"), 4, "qc", (batch_no, reason)))

    ops.sort(key=lambda o: (o[0], o[1]))

    batch_ids = {}   # 批号 -> batch_id（入库后才知道）
    transfer_ids = {}  # (批号, 调出, 调入, 发货日) -> transfer_id
    for when, _prio, kind, payload in ops:
        if kind == "inbound":
            drug_code, batch_no, prod, exp, supplier, qty = payload
            item = SimpleNamespace(drug_id=drug_ids[drug_code], batch_no=batch_no,
                                   production_date=_d(prod), expiry_date=_d(exp),
                                   quantity=qty, supplier=supplier)
            create_inbound(db, store_id=store_ids[WH], operator=OPERATORS[WH],
                           items=[item], note="种子期初入库", when=when)
            from .models import Batch
            batch_ids[batch_no] = db.query(Batch).filter(
                Batch.drug_id == drug_ids[drug_code], Batch.batch_no == batch_no).first().id
        elif kind == "ship":
            batch_no, frm, to, qty = payload
            t = create_transfer(db, from_store_id=store_ids[frm],
                                to_store_id=store_ids[to], batch_id=batch_ids[batch_no],
                                quantity=qty, operator=OPERATORS[frm], when=when)
            transfer_ids[(batch_no, frm, to)] = t.id
        elif kind == "receive":
            batch_no, frm, to, qty = payload
            receive_transfer(db, transfer_id=transfer_ids[(batch_no, frm, to)],
                             operator=OPERATORS[to], when=when)
        elif kind == "sale":
            store, drug_code, qty, otype = payload
            item = SimpleNamespace(drug_id=drug_ids[drug_code], quantity=qty, allocations=None)
            create_outbound(db, store_id=store_ids[store], order_type=otype,
                            operator=OPERATORS[store], items=[item], when=when)
        elif kind == "qc":
            batch_no, reason = payload
            suspend_batch(db, batch_id=batch_ids[batch_no], reason=reason,
                          operator="质检员-赵敏", when=when)

    # 截至今天，过有效期的批次整批锁死（CTR2409B）
    locked = apply_expiry_locks(db, date.today())
    db.commit()
    print(f"[种子] 完成：{len(DRUGS)} 药品 / {len(BATCHES)} 批次 / {len(STORES)} 门店，"
          f"过期锁定 {len(locked)} 批", flush=True)


def seed_if_empty() -> bool:
    init_db()
    db = SessionLocal()
    try:
        if db.query(Drug).count() > 0:
            return False
        _seed(db)
        return True
    finally:
        db.close()


